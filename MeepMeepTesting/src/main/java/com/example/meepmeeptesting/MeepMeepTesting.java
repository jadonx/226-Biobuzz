package com.example.meepmeeptesting;

import com.acmerobotics.roadrunner.Pose2d;
import com.acmerobotics.roadrunner.Vector2d;
import com.noahbres.meepmeep.MeepMeep;
import com.noahbres.meepmeep.roadrunner.DefaultBotBuilder;
import com.noahbres.meepmeep.roadrunner.entity.RoadRunnerBotEntity;

import java.io.File;
import java.io.IOException;

import javax.imageio.ImageIO;

import sun.lwawt.macosx.CImage;

public class MeepMeepTesting {
    public static void main(String[] args) {
        MeepMeep meepMeep = new MeepMeep(800);

        RoadRunnerBotEntity myBot = new DefaultBotBuilder(meepMeep)
                .setConstraints(50, 50, Math.toRadians(180), Math.toRadians(180), 15)
                .build();
        Pose2d startPose = new Pose2d(-63, -24, Math.toRadians(0));

        myBot.runAction(myBot.getDrive().actionBuilder(startPose)
                // depart to shooting range
                .lineToX(-36)
                // pause to show and aim at (0,0)
                .waitSeconds(2.0)
                // return to park in alliance load zone
                .strafeTo(new Vector2d(-60, -48))
                .build());
        meepMeep.setBackground(ImageIO.read("226-Biobuzz/Me]\epMeepTesting/res/biobuzz-custom"))
                .setDarkMode(true)
                .setBackgroundAlpha(0.95f)
                .addEntity(myBot)
                .start();
    }

}



